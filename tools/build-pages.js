/* Makes the site findable on Google in every language.
   - writes the search title, description, share image, language links and structured data into index.html
   - creates fr/index.html, ar/index.html and de/index.html: the same page, opening in that language
   - writes sitemap.xml and robots.txt
   Run by "Update website.bat". The public address comes from tools/site.json. */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const cfg = JSON.parse(fs.readFileSync(path.join(__dirname, 'site.json'), 'utf8'));
const URL = cfg.url.endsWith('/') ? cfg.url : cfg.url + '/';
const LANGS = ['en', 'fr', 'ar', 'de'], OG = { en: 'en_US', fr: 'fr_FR', ar: 'ar_DZ', de: 'de_DE' };
const pageUrl = l => (l === 'en' ? URL : URL + l + '/');
const esc = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
const START = '<!-- seo:start (written by tools/build-pages.js) -->', END = '<!-- seo:end -->';

const ld = {
  '@context': 'https://schema.org',
  '@graph': [
    { '@type': 'Person', '@id': URL + '#nazih', name: 'Nazih Talbi', alternateName: 'نزيه طالبي', jobTitle: 'Videographer and photographer', url: URL,
      image: URL + 'assets/media/site/case-masaar-1.webp', email: 'mailto:nazihhtalbi@gmail.com', telephone: '+213779072740',
      sameAs: ['https://www.instagram.com/NA_Z_IH1'], knowsLanguage: ['ar', 'fr', 'en', 'de'], address: { '@type': 'PostalAddress', addressCountry: 'DZ' } },
    { '@type': 'ProfessionalService', name: 'Nazih Talbi, videographer and photographer', url: URL, image: URL + 'assets/media/video/showreel.webp',
      founder: { '@id': URL + '#nazih' }, telephone: '+213779072740', email: 'nazihhtalbi@gmail.com', areaServed: { '@type': 'Country', name: 'Algeria' },
      address: { '@type': 'PostalAddress', addressCountry: 'DZ' },
      knowsAbout: ['Event videography', 'Documentary film', 'Short film', 'Commercials', 'Social media reels', 'Colour grading', 'Photography'] },
  ],
};

function head(l) {
  const s = cfg.seo[l];
  return [START,
    `<title>${esc(s.title)}</title>`,
    `<meta name="description" content="${esc(s.description)}">`,
    `<link rel="canonical" href="${pageUrl(l)}">`,
    ...LANGS.map(x => `<link rel="alternate" hreflang="${x}" href="${pageUrl(x)}">`),
    `<link rel="alternate" hreflang="x-default" href="${URL}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:url" content="${pageUrl(l)}">`,
    `<meta property="og:title" content="${esc(s.title)}">`,
    `<meta property="og:description" content="${esc(s.description)}">`,
    `<meta property="og:image" content="${URL}assets/media/video/showreel.webp">`,
    `<meta property="og:locale" content="${OG[l]}">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<script type="application/ld+json">${JSON.stringify(ld)}</script>`,
    END].join('\n');
}

let src = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
// first run: replace the old hand-written title / description / og lines with the generated block
if (!src.includes(START)) {
  src = src.replace(/<title>[\s\S]*?<meta property="og:image"[^>]*>/, START + '\n' + END);
  if (!src.includes(START)) throw new Error('could not find the <title> ... og:image lines in index.html');
}
const block = new RegExp(START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + END);
src = src.replace(block, head('en'));
src = src.replace(/<html lang="[^"]*" dir="[^"]*"( data-page-lang="[^"]*")?>/, '<html lang="en" dir="ltr">');
fs.writeFileSync(path.join(ROOT, 'index.html'), src);

for (const l of LANGS.slice(1)) {
  let p = src.replace(block, head(l))
    .replace('<html lang="en" dir="ltr">', `<html lang="${l}" dir="${l === 'ar' ? 'rtl' : 'ltr'}" data-page-lang="${l}">`)
    .replace(/(\s(?:src|href|poster))="assets\//g, '$1="../assets/')
    .replace('<script src="../assets/js/lang-detect.js"></script>', '<script>window.SITE_ROOT = "../";</script>\n<script src="../assets/js/lang-detect.js"></script>');
  fs.mkdirSync(path.join(ROOT, l), { recursive: true });
  fs.writeFileSync(path.join(ROOT, l, 'index.html'), '<!-- Generated by tools/build-pages.js from index.html. Do not edit: run "Update website.bat". -->\n' + p);
}

const today = new Date().toISOString().slice(0, 10);
fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${LANGS.map(l => `  <url>
    <loc>${pageUrl(l)}</loc>
    <lastmod>${today}</lastmod>
${LANGS.map(x => `    <xhtml:link rel="alternate" hreflang="${x}" href="${pageUrl(x)}"/>`).join('\n')}
    <xhtml:link rel="alternate" hreflang="x-default" href="${URL}"/>
  </url>`).join('\n')}
</urlset>
`);
fs.writeFileSync(path.join(ROOT, 'robots.txt'), `User-agent: *\nAllow: /\nDisallow: /tools/\n\nSitemap: ${URL}sitemap.xml\n`);
console.log(`Pages for ${LANGS.join(', ')} written for ${URL}`);
